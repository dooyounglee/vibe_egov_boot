-- =============================================================
-- TB_SURVEY / TB_SURVEY_QUESTION : 설문 / 설문 문항 (1:N 매핑 예시)
-- 반영 : DBA 수동 반영 (dev / prod)
-- 기준 : Oracle / Tibero 문법. 다른 DBMS는 타입을 맞춰 작성
-- 엔티티 : SurveyJpaEntity, SurveyQuestionJpaEntity (ddl-auto=validate 로 일치 여부 검증)
-- =============================================================

CREATE SEQUENCE SEQ_SURVEY START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_SURVEY_QUESTION START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE TB_SURVEY (
    SURVEY_ID   NUMBER(19)      NOT NULL,
    TITLE       VARCHAR2(100)   NOT NULL,
    CREATED_AT  TIMESTAMP       NOT NULL,
    CONSTRAINT PK_TB_SURVEY PRIMARY KEY (SURVEY_ID)
);

CREATE TABLE TB_SURVEY_QUESTION (
    QUESTION_ID NUMBER(19)      NOT NULL,
    SURVEY_ID   NUMBER(19)      NOT NULL,
    CONTENT     VARCHAR2(500)   NOT NULL,
    SORT_ORDER  NUMBER(5)       NOT NULL,
    CONSTRAINT PK_TB_SURVEY_QUESTION PRIMARY KEY (QUESTION_ID),
    CONSTRAINT FK_TB_SURVEY_QUESTION_01 FOREIGN KEY (SURVEY_ID) REFERENCES TB_SURVEY (SURVEY_ID)
);

-- Oracle 은 FK 컬럼에 인덱스를 자동으로 만들지 않는다
CREATE INDEX IX_TB_SURVEY_QUESTION_01 ON TB_SURVEY_QUESTION (SURVEY_ID);

COMMENT ON TABLE  TB_SURVEY                     IS '설문';
COMMENT ON COLUMN TB_SURVEY.SURVEY_ID           IS '설문ID';
COMMENT ON COLUMN TB_SURVEY.TITLE               IS '제목';
COMMENT ON COLUMN TB_SURVEY.CREATED_AT          IS '등록일시';

COMMENT ON TABLE  TB_SURVEY_QUESTION             IS '설문 문항';
COMMENT ON COLUMN TB_SURVEY_QUESTION.QUESTION_ID IS '문항ID';
COMMENT ON COLUMN TB_SURVEY_QUESTION.SURVEY_ID   IS '설문ID';
COMMENT ON COLUMN TB_SURVEY_QUESTION.CONTENT     IS '문항 내용';
COMMENT ON COLUMN TB_SURVEY_QUESTION.SORT_ORDER  IS '정렬순서';
